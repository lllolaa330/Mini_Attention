#!/usr/bin/env python3
"""Export the official SCNA-8 checkpoint as RNE binary16 coefficient functions."""
import argparse
import hashlib
import math
import struct
import zipfile
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from model.attention import encode
from model.scope_attention import EXP_COEFFICIENTS


CHECKPOINT_SHA256 = '9d3d346ace40c3b37415127d326834aafa868bfb8da016f0de30299ad8cd071a'


def extract(checkpoint):
    """Read the known raw FloatStorage ZIP payloads without unpickling."""
    if hashlib.sha256(checkpoint.read_bytes()).hexdigest() != CHECKPOINT_SHA256:
        raise ValueError('Unexpected SCOPE Exp8 checkpoint')
    prefix = 'best_mlp1_scalar_expo/'
    with zipfile.ZipFile(checkpoint) as archive:
        if archive.read(prefix + 'byteorder') != b'little':
            raise ValueError('Unexpected SCOPE checkpoint byte order')
        # fc1_weight_raw, fc1_bias_raw, fc2_weight_raw, each with 8 floats.
        raw = [struct.unpack('<8f', archive.read(prefix + f'data/{i}')) for i in range(3)]
    return tuple((encode(math.exp(w+k)), encode(math.exp(b+k))) for w, b, k in zip(*raw))


def render():
    rows = [
        '// Generated by scripts/gen_scope_exp.py from the MICRO 2026 SCOPE artifact.',
        '// Fused and rounded coefficients; upstream attribution in third_party/scope/README.md.',
    ]
    weights, biases = zip(*EXP_COEFFICIENTS)
    for name, values in [('scope_exp_weight', weights), ('scope_exp_bias', biases)]:
        rows.append(f'function automatic logic [15:0] {name}(input logic [2:0] neuron);')
        rows.append('    case (neuron)')
        for index, value in enumerate(values):
            rows.append(f"        3'd{index}: {name} = 16'h{value:04x};")
        rows.append(f"        default: {name} = 16'h0000;")
        rows.extend(['    endcase', 'endfunction', ''])
    return '\n'.join(rows)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check the checked-in RTL')
    parser.add_argument('--checkpoint', type=Path, help='verify coefficients against the pinned original .pth')
    args = parser.parse_args()
    if args.checkpoint and extract(args.checkpoint) != EXP_COEFFICIENTS:
        raise SystemExit('Software coefficients differ from the fused checkpoint')
    target = ROOT / 'rtl/scope_exp_coeffs.svh'
    if args.check:
        if target.read_text() != render():
            raise SystemExit('Generated SCOPE Exp8 coefficients differ')
        print('SCOPE Exp8 coefficient check passed')
    else:
        target.write_text(render())
